#!/usr/bin/env python3
"""HOLD-only visual preflight for an authentic UrAi Ascent capture.

This does NOT establish camera identity or visual quality by itself. It rejects
static skies, long black cuts and missing geometric motion in decoded pixels.
Final acceptance additionally requires same-file SHA-bound camera telemetry,
source-build provenance and independent human inspection.
No stills, synthetic motion or source footage are generated by this tool.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import re
import subprocess

W, H, FPS = 128, 72, 4
SCHEMA = 'urai-genesis-ascent-camera-pixel-proof-hold/v1'
MAX_VIDEO_BYTES = 256 * 1024 * 1024


class HoldRefusal(RuntimeError):
    pass


def require(test: bool, message: str):
    if not test:
        raise HoldRefusal(message)



def private_evidence_path(raw: str) -> Path:
    """Reject linked evidence paths, including junction ancestors and .git worktrees."""
    import os
    import stat
    require(isinstance(raw, str) and bool(raw) and chr(0) not in raw,
            'PRIVATE_EVIDENCE_PATH_REQUIRED')
    target = Path(os.path.abspath(raw))
    for component in (target, *target.parents):
        try:
            info = component.lstat()
        except FileNotFoundError:
            continue
        mode = info.st_mode
        require(not stat.S_ISLNK(mode), 'PRIVATE_EVIDENCE_SYMLINK_PATH_FORBIDDEN')
        # On Python 3.11 a Windows junction may not expose Path.is_junction().
        # Inspect the Win32 reparse attribute directly; fail closed on any
        # linked/reparse ancestor, even when its target is not a checkout.
        require(not (getattr(info, 'st_file_attributes', 0) &
                     getattr(stat, 'FILE_ATTRIBUTE_REPARSE_POINT', 0x400)),
                'PRIVATE_EVIDENCE_SYMLINK_PATH_FORBIDDEN')
        junction = getattr(component, 'is_junction', None)
        if junction is not None:
            require(not junction(), 'PRIVATE_EVIDENCE_SYMLINK_PATH_FORBIDDEN')
        if stat.S_ISDIR(mode):
            try:
                (component / '.git').lstat()
            except FileNotFoundError:
                pass
            else:
                raise HoldRefusal('PRIVATE_EVIDENCE_INSIDE_GIT_CHECKOUT')
    return target

def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open('rb') as fd:
        for buf in iter(lambda: fd.read(1024 * 1024), b''):
            h.update(buf)
    return h.hexdigest()


def probe(path: Path) -> dict:
    cmd = ['ffprobe', '-v', 'error', '-show_entries',
           'format=duration:stream=codec_type,codec_name,width,height',
           '-of', 'json', str(path)]
    r = subprocess.run(cmd, capture_output=True, timeout=20)
    require(r.returncode == 0, 'FFPROBE_REJECTED_INPUT')
    data = json.loads(r.stdout)
    video = next((s for s in data.get('streams', []) if s.get('codec_type') == 'video'), None)
    require(video and video.get('width', 0) >= 320 and video.get('height', 0) >= 180,
            'ORIGINAL_VIDEO_DIMENSIONS_UNVERIFIED')
    duration = float(data.get('format', {}).get('duration', 0))
    require(math.isfinite(duration) and 3.9 <= duration <= 25, 'ASCENT_VIDEO_DURATION_INVALID')
    return {'durationSeconds': duration, 'codec': video.get('codec_name'),
            'width': video['width'], 'height': video['height']}


def decoded_frames(path: Path, duration: float) -> list[bytes]:
    # FFmpeg is the renderer of *decoded frames only*, never an animated editor.
    args = ['ffmpeg', '-nostdin', '-v', 'error', '-i', str(path), '-an',
            '-vf', f'fps={FPS},scale={W}:{H}:flags=bilinear,format=gray',
            '-f', 'rawvideo', '-pix_fmt', 'gray', '-']
    r = subprocess.run(args, capture_output=True, timeout=65)
    require(r.returncode == 0, 'ORIGINAL_VIDEO_DECODE_FAILED')
    sz = W * H
    require(len(r.stdout) % sz == 0, 'INCOMPLETE_DECODED_FRAME')
    frames = [r.stdout[i:i + sz] for i in range(0, len(r.stdout), sz)]
    require(len(frames) >= max(12, int((duration - .3) * FPS)),
            'DECODED_ASCENT_FRAME_COUNT_TOO_LOW')
    return frames


def coarse(frame: bytes) -> list[float]:
    # Spatial averages suppress twinkling stars or flicker from a few pixels.
    result = []
    for by in range(0, H, 12):
        for bx in range(0, W, 16):
            result.append(sum(frame[y * W + x]
                              for y in range(by, by + 12)
                              for x in range(bx, bx + 16)) / 192)
    return result


def flow_tiles(previous: bytes, current: bytes) -> int:
    """Count textured 12x12 tiles whose best vertical shift improves matching.

    Nonzero geometric displacement is evidence of pixel motion, NOT proof of
    world-space camera ascent. The independent camera and human gates remain.
    """
    tiles = 0
    for y in (17, 32, 47):
        for x in (27, 45, 63, 81, 99):
            vals = [previous[(y + j) * W + x + i]
                    for j in range(-5, 7, 2) for i in range(-5, 7, 2)]
            mean = sum(vals) / len(vals)
            variance = sum((p - mean) ** 2 for p in vals) / len(vals)
            if variance < 95:
                continue
            def sad(dx: int, dy: int) -> float:
                return sum(abs(previous[(y + j) * W + x + i] -
                               current[(y + j + dy) * W + x + i + dx])
                           for j in range(-5, 7, 2)
                           for i in range(-5, 7, 2)) / len(vals)
            zero = sad(0, 0)
            if zero < 3:
                continue
            best = (zero, 0, 0)
            for dy in (-4, -3, -2, -1, 1, 2, 3, 4):
                for dx in (-4, -2, 0, 2, 4):
                    score = sad(dx, dy)
                    if score < best[0]:
                        best = (score, dx, dy)
            if best[2] and best[0] < zero * .78:
                tiles += 1
    return tiles


def inspect_pixels(frames: list[bytes], duration: float) -> dict:
    require(len(frames) >= 12 and all(len(f) == W * H for f in frames),
            'PIXEL_FRAMES_MISSING')
    averages = [sum(f) / len(f) for f in frames]
    # Require majority of pixels to be visible rather than a black cut.
    dark = [m < 14 for m in averages]
    longest_black = 0
    current_black = 0
    for flag in dark:
        current_black = current_black + 1 if flag else 0
        longest_black = max(longest_black, current_black)
    low = [coarse(f) for f in frames]
    moving = []
    geometric = []
    for k, (a, b) in enumerate(zip(frames, frames[1:])):
        mad = sum(abs(x - y) for x, y in zip(a, b)) / len(a)
        structure = sum(abs(x - y) for x, y in zip(low[k], low[k+1])) / len(low[k])
        moving.append(mad >= 2.5 and structure >= 1.25)
        geometric.append(flow_tiles(a, b))
    longest_static = 0
    current_static = 0
    for flag in moving:
        current_static = 0 if flag else current_static + 1
        longest_static = max(longest_static, current_static)
    result = {
        'samplingFps': FPS, 'decodedFrames': len(frames),
        'movingPairs': sum(moving), 'totalPairs': len(moving),
        'coherentGeometryPairs': sum(t >= 3 for t in geometric),
        'maxConsecutiveDarkFrames': longest_black,
        'maxConsecutiveStaticPairs': longest_static,
        'darkFrames': sum(dark),
        'durationSeconds': duration,
    }
    require(longest_black <= 2 and sum(dark) <= max(3, int(.15 * len(dark))),
            'DARK_CUT_OR_BLANK_SKY_DETECTED')
    require(sum(moving) >= max(5, int(.4 * len(moving))) and longest_static <= 4,
            'STATIONARY_OR_FROZEN_ASCENT_PIXELS')
    require(result['coherentGeometryPairs'] >= max(3, int(.2 * len(moving))),
            'NO_GEOMETRIC_SCENERY_MOTION_PROVEN')
    return result


def validate_camera_telemetry(record: dict, video_hash: str, video_duration: float | None = None) -> dict:
    """Validate contemporaneous DOM camera callbacks bound to the decoded file.

    Receipts must come from an authorized build of PR #1944 or successor, not
    the unchanged original static export, which lacks camera-tick attributes.
    """
    require(isinstance(record, dict) and record.get('schema') == SCHEMA,
            'CAMERA_TELEMETRY_SCHEMA_MISMATCH')
    sha = record.get('applicationRevision')
    require(isinstance(sha, str) and re.fullmatch('[a-f0-9]{40}', sha),
            'PATCHED_APPLICATION_REVISION_REQUIRED')
    require(sha != '94c8a2cf68a436a0c49e80b3a09578935df12d48',
            'ORIGINAL_STATIC_EXPORT_HAS_NO_CAMERA_TICK_TELEMETRY')
    require(record.get('buildProvenance') == 'DECLARED_SHA_NOT_INDEPENDENTLY_ATTESTED',
            'INDEPENDENT_BUILD_PROVENANCE_STILL_REQUIRED')
    require(record.get('sourceVideoSha256') == video_hash,
            'CAMERA_TO_VIDEO_SOURCE_IDENTITY_MISMATCH')
    require(record.get('fixture') == 'EXPLICIT_DISCLOSED_DEMO_QUIET_RESET_NO_PERSONAL_ACCOUNT',
            'SAMPLE_FIXTURE_AUTHORITY_REQUIRED')
    samples = record.get('samples')
    require(isinstance(samples, list) and len(samples) >= 10,
            'INSUFFICIENT_ASCENT_CAMERA_SAMPLES')
    prev_tick = -1
    prev_time = -1.0
    prev_progress = -1.0
    for item in samples:
        require(isinstance(item, dict), 'INVALID_CAMERA_SAMPLE')
        tick, tm, progress, position = (item.get(k) for k in ('ticks', 'seconds', 'progress', 'position'))
        require(type(tick) is int and tick > prev_tick, 'FROZEN_ASCENT_CAMERA_CALLBACKS')
        require(all(type(v) in (int,float) and math.isfinite(v) for v in (tm, progress)),
                'NONFINITE_ASCENT_TIMING')
        require(tm > prev_time and progress >= prev_progress - .01 and 0 <= progress <= 1.01,
                'NONMONOTONIC_CAMERA_TIMING_OR_PROGRESS')
        require(isinstance(position, list) and len(position) == 3 and
                all(type(v) in (int,float) and math.isfinite(v) for v in position),
                'INVALID_CAMERA_POSITION')
        prev_tick, prev_time, prev_progress = tick, tm, progress
    vertical = [b['position'][1] - a['position'][1] for a, b in zip(samples, samples[1:])]
    require(sum(delta > .05 for delta in vertical) >= .65 * len(vertical) and
            all(delta >= -.20 for delta in vertical),
            'CONTINUOUS_UPWARD_CAMERA_PATH_NOT_PROVEN')
    climb = samples[-1]['position'][1] - samples[0]['position'][1]
    require(max(vertical) < .45 * max(1, climb), 'DISCONTINUOUS_CAMERA_TELEPORT_DETECTED')
    elapsed = samples[-1]['seconds'] - samples[0]['seconds']
    if video_duration is not None:
        require(samples[0]['seconds'] >= 0 and samples[-1]['seconds'] <= video_duration + .5,
                'CAMERA_TELEMETRY_OUTSIDE_RECORDED_VIDEO')
    require(climb >= 20 and elapsed >= 2.7 and samples[-1]['progress'] >= .9 and
            samples[0]['progress'] <= .12, 'REAL_CAMERA_CLIMB_UNPROVEN')
    return {'sourceRevision': sha, 'cameraSamples':len(samples),
            'cameraTickDelta':samples[-1]['ticks'] - samples[0]['ticks'],
            'cameraAltitudeDelta':round(climb, 3), 'cameraElapsedSeconds':round(elapsed, 3)}


def main() -> int:
    p = argparse.ArgumentParser(description='UrAi original WebGL Ascent: decoded-pixel preflight, not publication approval')
    p.add_argument('--video', required=True)
    p.add_argument('--camera-telemetry', help='Same-video SHA-bound DOM telemetry JSON from patched build')
    p.add_argument('--receipt', help='Private result JSON path; no raw frames saved')
    args = p.parse_args()
    result = {'schema': 'urai-genesis-ascent-pixel-inspection-hold/v1',
              'release': 'NO-GO/HOLD', 'publicPublishing': False,
              'independentHumanApproval': False, 'visuallyApproved': False}
    try:
        video = private_evidence_path(args.video)
        require(video.is_file() and not video.is_symlink() and
                8192 < video.stat().st_size <= MAX_VIDEO_BYTES,
                'GENUINE_ASCENT_SOURCE_VIDEO_MISSING_OR_UNSAFE')
        metadata = probe(video)
        frames = decoded_frames(video, metadata['durationSeconds'])
        result['videoSha256'] = sha256_file(video)
        result['probe'] = metadata
        result['pixels'] = inspect_pixels(frames, metadata['durationSeconds'])
        if not args.camera_telemetry:
            raise HoldRefusal('CAMERA_TELEMETRY_REQUIRED_FOR_PHYSICAL_ASCENT_PRECHECK')
        with private_evidence_path(args.camera_telemetry).open('r', encoding='utf8') as f:
            camera = json.load(f)
        result['camera'] = validate_camera_telemetry(camera, result['videoSha256'], metadata['durationSeconds'])
        result['status'] = 'PIXEL_AND_CAMERA_PREFLIGHT_PASSED_HUMAN_REVIEW_REQUIRED'
    except (HoldRefusal, ValueError, OSError, json.JSONDecodeError,
            subprocess.TimeoutExpired) as e:
        result['status'] = 'HOLD_FAIL'
        result['reason'] = str(e)[:350]
    if args.receipt:
        dest = private_evidence_path(args.receipt)
        require(dest.parent.is_dir(), 'RECEIPT_PARENT_DOES_NOT_EXIST')
        with dest.open('x', encoding='utf8') as output:
            output.write(json.dumps(result, indent=2) + '\n')
    print(json.dumps(result, indent=2))
    return 0 if result['status'].startswith('PIXEL_AND_CAMERA_PREFLIGHT_PASSED') else 2


if __name__ == '__main__':
    raise SystemExit(main())
