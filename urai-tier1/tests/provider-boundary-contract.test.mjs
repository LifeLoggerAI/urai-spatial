import assert from 'node:assert/strict'
import fs from 'node:fs'
import test from 'node:test'

const read = (path) => fs.readFileSync(new URL(path, import.meta.url), 'utf8')
const boundary = read('../src/lib/server/provider-boundary.ts')
const openaiRoute = read('../src/app/api/urai/orb/openai/route.ts')
const openaiClient = read('../src/spatial/orb/openaiClient.ts')
const orbPanel = read('../src/spatial/orb/OrbConversationPanel.tsx')
const elevenlabs = read('../src/lib/server/elevenlabs-synthesis.ts')
const narratorClient = read('../src/spatial/narrator/elevenlabsClient.ts')
const narratorPlayback = read('../src/spatial/narrator/narratorPlayback.ts')
const narratorRoute = read('../src/app/api/urai/narrator/elevenlabs/route.ts')
const voiceRoute = read('../src/app/api/voice/elevenlabs/route.ts')

function compact(value) {
  return value.replace(/\s+/g, ' ')
}

test('provider boundary requires saved, fully enforced model consent and durable throttling', () => {
  assert.match(boundary, /explicitConsent/)
  assert.match(boundary, /users\/\$\{input\.uid\}\/privacyPolicy\/current/)
  assert.match(boundary, /mode !== 'granted'/)
  assert.match(boundary, /models\.modelContext !== true/)
  assert.match(boundary, /fully-enforced/)
  assert.match(boundary, /providerConnections\/\$\{input\.provider\}/)
  assert.match(boundary, /PROVIDER_PROCESSING_REVOKED/)
  assert.match(boundary, /runTransaction/)
  assert.match(boundary, /providerRateLimits/)
  assert.match(boundary, /providerTelemetry/)
  assert.doesNotMatch(boundary, /prompt:/i)
  assert.doesNotMatch(boundary, /generatedText/i)
})

test('OpenAI Orb is server-only, authenticated, moderated, non-stored, structured and cancellation-bounded', () => {
  assert.match(openaiRoute, /verifyFirebaseUser/)
  assert.match(openaiRoute, /authorizeExternalProviderRequest/)
  assert.match(openaiRoute, /consumeProviderRateLimit/)
  assert.match(openaiRoute, /process\.env\.OPENAI_API_KEY/)
  assert.match(openaiRoute, /https:\/\/api\.openai\.com\/v1\/moderations/)
  assert.match(openaiRoute, /omni-moderation-latest/)
  assert.match(openaiRoute, /https:\/\/api\.openai\.com\/v1\/responses/)
  assert.match(openaiRoute, /store: false/)
  assert.match(openaiRoute, /stream: true/)
  assert.match(openaiRoute, /safety_identifier/)
  assert.match(openaiRoute, /type: 'json_schema'/)
  assert.match(openaiRoute, /strict: true/)
  assert.match(openaiRoute, /response\.output_text\.delta/)
  assert.match(openaiRoute, /boundedAbortSignal/)
  assert.match(openaiRoute, /Cache-Control': 'private, no-store/)
  assert.doesNotMatch(openaiRoute, /console\.(log|info|error|warn)\([^)]*(message|context)/)
})

