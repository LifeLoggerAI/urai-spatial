test('Narrator consent is session-only, off by default, immediately revocable and cache-bounded', () => {
  const playback = compact(narratorPlayback)
  assert.match(narratorClient, /externalProcessingConsent = false/)
  assert.match(narratorClient, /MAX_MEMORY_CACHE_ENTRIES = 12/)
  assert.match(narratorClient, /cache: "no-store"/)
  assert.doesNotMatch(narratorClient, /for \(let attempt/)
  assert.match(playback, /private externalVoiceConsent = false/)
  assert.match(playback, /setExternalVoiceConsent\(allowed: boolean\)/)
  assert.match(playback, /if \(!this\.externalVoiceConsent && this\.aborter\) this\.aborter\.abort\(\)/)
  assert.match(playback, /this\.externalVoiceConsent/)
  assert.match(orbPanel, /setExternalVoiceConsent\(false\)/)
})
