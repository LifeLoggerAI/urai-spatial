  assert.match(geology, /function createLivingMemoryFold\(/)
  assert.match(geology, /const furrow = Math\.exp\(-Math\.pow\(lateral \/ \.20, 2\)\)/)
  assert.match(geology, /- \.070 \* furrow/)
